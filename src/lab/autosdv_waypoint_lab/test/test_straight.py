"""The straight test routes (lab2_straight_*): generated on the U-turn's field. No ROS."""
import os

import pytest
import yaml

from autosdv_waypoint_lab import course as course_mod
from autosdv_waypoint_lab import straight

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COURSES = os.path.join(HERE, 'config', 'courses')


def _yaml(d):
    with open(os.path.join(d, 'course.yaml')) as f:
        return yaml.safe_load(f)


def test_the_path_runs_plus_x_from_the_start_box():
    lay = straight.make_layout(3.0)
    assert lay.xs[0] == 0.0 and lay.xs[-1] == pytest.approx(3.0)
    assert all(y == 0.0 for y in lay.ys)
    steps = [b - a for a, b in zip(lay.xs, lay.xs[1:])]
    assert all(s == pytest.approx(0.25) for s in steps)
    assert lay.start == (0.0, 0.0, 0.0)
    assert lay.stop == (pytest.approx(3.0), 0.0)


def test_the_boards_and_frame_are_the_uturns():
    lay = straight.make_layout(3.0)
    uturn = course_mod.load_course(os.path.join(COURSES, 'lab2_uturn'))
    assert [(b.id, b.x, b.y, b.yaw) for b in lay.boards] == \
        [(m.id, m.x, m.y, m.yaw) for m in uturn.markers]
    d = yaml.safe_load(straight.course_yaml(lay).split('\nfield:', 1)[0] + '\n') or {}
    assert d == {}          # the header is comments only
    c = yaml.safe_load(straight.course_yaml(lay))
    assert c['field'] == 'lab2_uturn'
    assert c['start_pose'] == {'x': 0.0, 'y': 0.0, 'yaw': 0.0}
    assert c['closed'] is False and c['laps'] == 1 and c['v_ref'] == 0.8
    assert c['marker_size'] == uturn.marker_size and c['dictionary'] == uturn.dictionary


def test_coverage_a_board_throughout_two_on_most():
    # 2 m: boards 24 and 25 throughout. 3 m: 25 leaves the camera's field at
    # s = 2.6 m, so the last 0.4 m (the end ramp and the stop) has 24 alone, 1.5 m ahead
    two = straight.make_layout(2.0)
    assert two.ok and two.fraction == 1.0 and two.two_fraction == 1.0
    lay = straight.make_layout(3.0)
    assert lay.start_box_min >= 2
    assert lay.fraction == 1.0
    assert lay.two_fraction >= 0.85
    assert lay.ok, lay.problems
    assert any('two or more' in w for w in lay.warnings)


def test_too_long_a_straight_is_refused():
    # board 24 stands at x = 4.5 on the line: the nose (0.5 m ahead) must stay 1 m short
    assert straight.make_layout(3.0).ok
    lay = straight.make_layout(3.5)
    assert any('board 24' in p for p in lay.problems), lay.problems


def test_the_header_is_generated_and_names_the_command():
    lay = straight.make_layout(3.0, v_ref=0.6, name='lab2_straight_slow')
    text = straight.course_yaml(lay)
    assert 'GENERATED by `just lab2 make-straight 3 --speed 0.6 --name lab2_straight_slow --write`' in text
    assert 'do not edit' in text
    assert 'id 24' in text
    assert yaml.safe_load(text)['v_ref'] == 0.6


def test_default_name():
    assert straight.default_name(3.0) == 'lab2_straight_3m'
    assert straight.default_name(2.5) == 'lab2_straight_2.5m'


def test_dry_run_writes_nothing_and_write_writes_the_course(tmp_path, capsys):
    out = tmp_path / 'lab2_straight_3m'
    assert straight.main(['3', '--out', str(out)]) == 0
    assert not out.exists()
    text = capsys.readouterr().out
    assert 'dry run' in text and 'two or more' in text
    assert straight.main(['3', '--out', str(out), '--write']) == 0
    assert sorted(os.listdir(out)) == ['ar_tag.param.yaml', 'course.yaml', 'lanelet2_map.osm',
                                       'map_projector_info.yaml', 'path.csv']
    c = course_mod.load_course(str(out))
    assert (out / 'lanelet2_map.osm').read_text() == course_mod.make_osm(c)
    assert (out / 'ar_tag.param.yaml').read_text() == course_mod.make_ar_tag_params(c)


def test_write_refuses_a_layout_that_misses_a_goal(tmp_path):
    out = tmp_path / 'long'
    assert straight.main(['3.5', '--out', str(out), '--write']) == 1
    assert not out.exists()


@pytest.mark.parametrize('name,length', [('lab2_straight_2m', 2.0), ('lab2_straight_3m', 3.0)])
def test_shipped_straights_are_up_to_date(name, length):
    """Regenerate with `just lab2 make-straight LENGTH --write` (also after the
    U-turn's boards move: the straights stand on its field)."""
    d = os.path.join(COURSES, name)
    lay = straight.make_layout(length)
    for fname, text in straight.files(lay, d).items():
        with open(os.path.join(d, fname)) as f:
            assert f.read() == text, f'{name}/{fname}: run just lab2 make-straight {length:g} --write'
    assert _yaml(d)['field'] == 'lab2_uturn'
